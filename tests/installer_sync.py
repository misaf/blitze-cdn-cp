"""Copy the blitzecdn_docker role's Docker setup into install.sh.

Run through `just installer-sync`; `--check` fails instead of writing.

install.sh has to install Docker before the control-plane image can run the
role, and it is downloaded on its own, so it cannot read the role's files. It
carries a generated copy instead, between two marker lines: the package list
and paths from defaults/main.yml, the apt source from templates/docker.sources.j2
and files/daemon.json verbatim. The role stays the only place they are edited,
and the bootstrap seeds the host with exactly what the role later finds.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
SCRIPT = REPO / "install.sh"
ROLE = REPO / "src/blitzecdn/assets/ansible/roles/blitzecdn_docker"
BEGIN = (
    "# >>> generated by `just installer-sync` from roles/blitzecdn_docker;"
    " edit the role, not this block\n"
)
END = "# <<< end of the generated blitzecdn_docker block\n"

# What each Jinja expression in docker.sources.j2 becomes in the bash function.
# Anything else in the template is refused: the bootstrap has no Jinja.
SOURCES_EXPRESSIONS = {
    "blitzecdn_docker_repository_url": "${repository_url}",
    "ansible_facts.distribution_release": "${codename}",
    "blitzecdn_docker_architecture": "${architecture}",
    "blitzecdn_docker_keyring": "${DOCKER_KEYRING}",
}
# Written unquoted into bash, so held to characters that need no quoting.
PLAIN = re.compile(r"[A-Za-z0-9_./+-]+")


def _plain(value: object, name: str) -> str:
    if not isinstance(value, str) or not PLAIN.fullmatch(value):
        raise SystemExit(f"error: {name} must be a plain word, got {value!r}")
    return value


def _sources_body() -> str:
    template = (ROLE / "templates/docker.sources.j2").read_text(encoding="utf-8")
    if re.search(r"[$`\\]|\{%|\{#", template):
        raise SystemExit(
            "error: docker.sources.j2 may only use {{ name }} substitutions;"
            " the bootstrap renders it as a bash here-document"
        )

    def substitute(match: re.Match[str]) -> str:
        expression = match.group(1)
        if expression not in SOURCES_EXPRESSIONS:
            raise SystemExit(
                f"error: docker.sources.j2 uses {{{{ {expression} }}}}, which"
                f" {Path(__file__).name} does not know how to give the bootstrap"
            )
        return SOURCES_EXPRESSIONS[expression]

    return re.sub(r"\{\{\s*(.*?)\s*\}\}", substitute, template)


def _verbatim(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    if not text.endswith("\n") or "\nBLITZECDN_EOF\n" in f"\n{text}":
        raise SystemExit(f"error: {path.name} cannot be carried as a here-document")
    return text


def generated_block() -> str:
    """The block install.sh has to carry, markers included."""
    defaults = yaml.safe_load((ROLE / "defaults/main.yml").read_text(encoding="utf-8"))
    keyring = _plain(defaults["blitzecdn_docker_keyring"], "blitzecdn_docker_keyring")
    sources_file = _plain(
        defaults["blitzecdn_docker_list_file"], "blitzecdn_docker_list_file"
    )
    daemon_file = _plain(
        defaults["blitzecdn_docker_daemon_config_file"],
        "blitzecdn_docker_daemon_config_file",
    )
    packages = " ".join(
        _plain(package, "blitzecdn_docker_packages")
        for package in defaults["blitzecdn_docker_packages"]
    )
    return (
        BEGIN
        + f"DOCKER_KEYRING={keyring}\n"
        + f"DOCKER_SOURCES_FILE={sources_file}\n"
        + f"DOCKER_DAEMON_CONFIG_FILE={daemon_file}\n"
        + f"DOCKER_PACKAGES=({packages})\n"
        + "\n"
        + "# templates/docker.sources.j2, for: ID VERSION_CODENAME ARCHITECTURE\n"
        + "docker_sources() {\n"
        + '  local repository_url="https://download.docker.com/linux/$1"'
        + " codename=$2 architecture=$3\n"
        + "  cat <<BLITZECDN_EOF\n"
        + _sources_body()
        + "BLITZECDN_EOF\n"
        + "}\n"
        + "\n"
        + "# files/daemon.json\n"
        + "docker_daemon_json() {\n"
        + "  cat <<'BLITZECDN_EOF'\n"
        + _verbatim(ROLE / "files/daemon.json")
        + "BLITZECDN_EOF\n"
        + "}\n"
        + END
    )


def synced(script: str) -> str:
    """install.sh with its generated block replaced by the current one."""
    if script.count(BEGIN) != 1 or script.count(END) != 1:
        raise SystemExit("error: install.sh must hold exactly one generated block")
    start = script.index(BEGIN)
    end = script.index(END) + len(END)
    return script[:start] + generated_block() + script[end:]


def main(arguments: list[str]) -> int:
    script = SCRIPT.read_text(encoding="utf-8")
    current = synced(script)
    if current == script:
        return 0
    if "--check" in arguments:
        print(
            "error: install.sh is out of date with roles/blitzecdn_docker;"
            " run `just installer-sync`",
            file=sys.stderr,
        )
        return 1
    SCRIPT.write_text(current, encoding="utf-8")
    print("Updated install.sh from roles/blitzecdn_docker.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
